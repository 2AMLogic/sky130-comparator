#!/usr/bin/env python3
"""Forward (#171) and supplemental reverse (#170) regeneration ladder: a `klt sim` request builder and
grader. Decision record: spec/decision-records/DR-008-forward-ladder-bench.md.

Why a request builder and not run.py or the op-only harness: see DR-008. In
short, the ladder is a PVT grid of one transient with `.meas` cards, which is
exactly what a `klt sim` request expresses, and `klt sim` is the path that
fans a grid out to the batch fleet.

    python3 sim/comparator-regeneration/ladder.py build  OUT_DIR [--sabotage-polarity] [--no-reverse] [--suppress-reverse-flip]
        writes OUT_DIR/{tb_regeneration.spice,request-<axis>.json}
    python3 sim/comparator-regeneration/ladder.py grade  RESPONSE.json [--expect-fail]
        grades a `klt sim --format json` response against ladder.json's
        checks plus the per-axis spread floors klt sim cannot express;
        also REPORTS the reverse ladder (never scored). With --reverse it
        grades the reverse checks only (the reverse negative control)

Then, per request:  klt sim OUT_DIR/request-<axis>.json --format json -o OUT_DIR/out-<axis>
(KLT_SIM_BACKEND=batch on a dispatch worker sends it to the fleet), and
`grade` takes every response: grade RESP1.json RESP2.json ...
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SIM_DIR = HERE.parent
MANIFEST = HERE / "testbench" / "ladder.json"
DUT_FRAGMENT = SIM_DIR / "comparator-decision" / "testbench" / "comparator_core.spice"
SPICEINIT = SIM_DIR / "spiceinit"

RUNGS = (("a", 50e-3), ("b", 1e-3), ("c", 0.1e-3))
T_FLIP_NS = 25  # input flips in the reset gap (clk low 20.1-40 ns): settled before strobe 2
DUT_PORTS = "CLK VDD GND VINP VINN OUTP OUTN"


def load_manifest() -> dict:
    return json.loads(MANIFEST.read_text())


def _fmt(x: float) -> str:
    return f"{x:.6g}"


def build_netlist(dut_text: str | None = None, sabotage_polarity: bool = False,
                  reverse: bool = True, suppress_reverse_flip: bool = False) -> str:
    """Forward ladder (byte-identical to the issue #171 netlist) plus, when
    `reverse`, the supplemental reverse block appended after it."""
    text = build_forward_netlist(dut_text, sabotage_polarity)
    if reverse:
        text += build_reverse_block(suppress_reverse_flip)
    return text


def build_reverse_block(suppress_flip: bool = False) -> str:
    """Supplemental reverse-polarity ladder (issue #170): mirrored instances
    r<rung>, input POSITIVE at strobe 1 and NEGATIVE at strobe 2 (HIGH->LOW
    decision), same rungs/strobes as the forward ladder. All three rungs sit
    on the main vdd/clk (ideal sources, so the forward devices and the
    vsupa-based energy measures are electrically independent of them).
    `suppress_flip` is the negative control: the stimulus never flips, so the
    second-strobe decision never happens and the reverse checks must fail."""
    s1, s2 = (+1, +1) if suppress_flip else (+1, -1)
    L: list[str] = ["", "* ---- supplemental reverse ladder (issue #170): reported, never scored"]
    a = L.append
    for r, dv in RUNGS:
        a(f"vsr{r} sr{r} 0 pwl(0 {_fmt(s1 * dv)} {T_FLIP_NS}n {_fmt(s1 * dv)} {T_FLIP_NS + 1}n {_fmt(s2 * dv)})")
        a(f"Epr{r} ipr{r} cm sr{r} 0 0.5")
        a(f"Enr{r} inr{r} cm sr{r} 0 -0.5")
        a(f"Xr{r} clk vdd 0 ipr{r} inr{r} opr{r} onr{r} comparator_dut")
        a(f"Bdr{r}n dr{r}n 0 v='0.5+(v(opr{r})-v(onr{r}))/(2*v(vdd))'")
    return "\n".join(L) + "\n"


def build_forward_netlist(dut_text: str | None = None, sabotage_polarity: bool = False) -> str:
    """Circuit-body netlist (no .control/.end; klt sim owns those).

    Each rung's differential input is a PWL that is NEGATIVE for strobe 1 and
    POSITIVE for strobe 2, so the timed decision is a flip against the
    opposite answer. `sabotage_polarity` swaps the signs: the negative control
    that the polarity checks must catch."""
    m = load_manifest()
    dut = DUT_FRAGMENT.read_text() if dut_text is None else dut_text
    s1, s2 = (+1, -1) if sabotage_polarity else (-1, +1)
    L: list[str] = []
    a = L.append
    a("* tb_regeneration -- forward overdrive ladder (issue #171), GENERATED by")
    a("* sim/comparator-regeneration/ladder.py; do not hand-edit.")
    a("* Circuit body for `klt sim`: models, .temp, supply alter and the control")
    a("* block are klt's. Rungs: A 50 mV (own supply vdda, for the energy")
    a("* integral), B 1 mV, C 0.1 mV; differential input +/-dv, Vcm = VDD/2.")
    a(f".options {' '.join(m['options'])}")
    a("")
    a(f".subckt comparator_dut {DUT_PORTS}")
    a(dut.rstrip())
    a(".ends comparator_dut")
    a("")
    a("vsup  vdd  0 dc 1.8")
    a("vsupa vdda 0 dc 1.8")
    a("* two strobes: evaluate 10-20 ns and 40-50 ns, clock scaled to the supply")
    a("vclkr clkr 0 pulse(0 1 10n 100p 100p 10n 30n)")
    a("Bclk  clk  0 v='v(clkr)*v(vdd)'")
    a("Bclka clka 0 v='v(clkr)*v(vdda)'")
    a("Bcm   cm   0 v='0.5*v(vdd)'")
    a("Bcma  cma  0 v='0.5*v(vdda)'")
    for r, dv in RUNGS:
        sup, cm, clk = ("vdda", "cma", "clka") if r == "a" else ("vdd", "cm", "clk")
        a("")
        a(f"* ---- rung {r}: {dv * 1e3:g} mV overdrive")
        a(f"vs{r} s{r} 0 pwl(0 {_fmt(s1 * dv)} {T_FLIP_NS}n {_fmt(s1 * dv)} {T_FLIP_NS + 1}n {_fmt(s2 * dv)})")
        a(f"Ep{r} ip{r} {cm} s{r} 0 0.5")
        a(f"En{r} in{r} {cm} s{r} 0 -0.5")
        a(f"X{r} {clk} {sup} 0 ip{r} in{r} op{r} on{r} comparator_dut")
        a(f"Bd{r}n d{r}n 0 v='0.5+(v(op{r})-v(on{r}))/(2*v({sup}))'")
    a("Bclkn clkn 0 v='v(clk)/v(vdd)'")
    return "\n".join(L) + "\n"


def _spiceinit_lines() -> list[str]:
    out = []
    for raw in SPICEINIT.read_text().splitlines():
        line = raw.split(";")[0].strip()
        if line and not line.startswith("*"):
            out.append(line)
    return out + ["set measureprec=12", "set numdgt=12"]


def _limits(check: dict) -> dict | None:
    lim = {k: check[k] for k in ("min", "max") if k in check}
    return lim or None


def build_requests(netlist_name: str = "tb_regeneration.spice", reverse: bool = True) -> dict[str, dict]:
    """The grid as four small `klt sim` requests, keyed by name.

    A single 45-point request was submitted to the batch fleet four times
    (timeout 300/60/120 s, with and without remote.hosts and max_workers)
    and every unit hit the per-unit timeout with ngspice parked after
    "Using KLU as Direct Linear Solver", while a 2-unit request of the same
    deck ran in 14 s per unit; so the grid is split into requests of <= 5
    units, which the fleet runs. Axes (one-at-a-time about tt/27C/1.8V, the
    sim/harness convention) plus the six non-baseline DR-005 graded corners:
      process      tt ss ff sf fs      @ 27C, 1.8 V
      temperature  tt                  @ -40 27 125 C, 1.8 V
      supply       tt                  @ 27C, 1.62 1.8 1.98 V
      graded-cold  ss sf fs @ -40C, 1.8 V
      graded-hot   ff sf fs @ 125C, 1.8 V   (together the six DR-005 corners)
    """
    m = load_manifest()
    v, tol = m["nominal_supply_v"], m["supply_tolerance"]
    lo, hi = round(v * (1 - tol), 6), round(v * (1 + tol), 6)
    meas: list[dict] = []
    # raw .meas cards first (reported, ungraded), then the derived names as
    # `.meas ... param=` cards so ngspice computes them in the same pass.
    for card in m["analyses"]:
        meas.append({"name": card.split()[2], "spice": card})
    for name, expr in m["measure"].items():
        entry = {"name": name, "spice": f".meas tran {name} param='{expr}'"}
        lim = _limits(m["checks"].get(name, {}))
        if lim:
            entry["limits"] = lim
        meas.append(entry)
    # reverse ladder: reported only, so NO klt-sim limits (never scored)
    rev = m.get("reverse_ladder")
    if reverse and rev:
        for card in rev["analyses"]:
            meas.append({"name": card.split()[2], "spice": card})
        for name, expr in rev["measure"].items():
            meas.append({"name": name, "spice": f".meas tran {name} param='{expr}'"})

    def req(process, temps, supplies, exclude=None):
        r = {
            "netlist": netlist_name,
            "engine": "ngspice",
            "models": {"pdk": "sky130A", "lib": "libs.tech/combined/sky130.lib.spice"},
            "corners": {"process": process,
                        "supply_v": {"vsup": supplies, "vsupa": supplies},
                        "temperature_c": temps},
            "analysis": m["analysis"],
            "measurements": meas,
            "options": {"timeout_s": 120, "keep_artifacts": True,
                        "ngspice_init": _spiceinit_lines()},
        }
        if exclude:
            r["exclude"] = exclude
        return r

    return {
        "process": req(m["process_corners"], [27], [v]),
        "temperature": req(["tt"], m["temperatures_c"], [v]),
        "supply": req(["tt"], [27], [lo, v, hi]),
        "graded-cold": req(["ss", "sf", "fs"], [-40], [v]),
        "graded-hot": req(["ff", "sf", "fs"], [125], [v]),
    }


# ---- grading ---------------------------------------------------------------

def _spread_pct(values: list[float]) -> float:
    if not values:
        return 0.0
    mean = abs(statistics.fmean(values)) or 1e-30
    return abs(max(values) - min(values)) / mean * 100.0


def _points(response: dict) -> list[dict]:
    pts = []
    for c in response["corners"]:
        vals = {x["name"]: x.get("value") for x in c["measurements"]}
        pts.append({"process": c["process"], "temp": float(c["temperature_c"]),
                    "supply": float(next(iter(c["supply_v"].values()))),
                    "id": c["corner_id"], "vals": vals})
    return pts


def axis_spreads(points: list[dict], names: list[str], nominal_v: float) -> dict:
    """One-at-a-time spreads about the tt/27C/nominal baseline (same
    definition as sim/harness/runner.py)."""
    def sl(name, **fixed):
        return [p["vals"][name] for p in points
                if all(p[k] == v for k, v in fixed.items()) and p["vals"].get(name) is not None]
    return {n: {"process": _spread_pct(sl(n, temp=27.0, supply=nominal_v)),
                "temperature": _spread_pct(sl(n, process="tt", supply=nominal_v)),
                "supply": _spread_pct(sl(n, process="tt", temp=27.0))} for n in names}


def merge_responses(responses: list[dict]) -> dict:
    """Union of several klt sim responses' corners, de-duplicated by corner_id
    (the tt/27C/1.8V baseline appears in every axis request)."""
    seen: dict[str, dict] = {}
    for r in responses:
        for c in r["corners"]:
            seen.setdefault(c["corner_id"], c)
    return {"corners": list(seen.values())}


def grade(response: dict, manifest: dict | None = None) -> list[str]:
    """Return a list of failure strings (empty == PASS). Per-point min/max
    come from the manifest (klt sim also grades them; re-checked here so a
    saved response can be graded offline), plus the spread floors."""
    m = manifest or load_manifest()
    pts = _points(response)
    fails: list[str] = []
    spreads = axis_spreads(pts, list(m["measure"]), m["nominal_supply_v"])
    for p in pts:
        for name, chk in m["checks"].items():
            val = p["vals"].get(name)
            if val is None or val != val:
                fails.append(f"{p['id']}: {name}: no value")
                continue
            if "min" in chk and val < chk["min"]:
                fails.append(f"{p['id']}: {name}={val:.6g} < min {chk['min']}")
            if "max" in chk and val > chk["max"]:
                fails.append(f"{p['id']}: {name}={val:.6g} > max {chk['max']}")
    for name, chk in m["checks"].items():
        for axis, floor in chk.get("min_spread_pct_by_axis", {}).items():
            s = spreads[name][axis]
            if s < floor:
                fails.append(f"{name}: {axis}-axis spread {s:.4g}% below floor {floor}%")
    return fails


def grade_reverse(response: dict, manifest: dict | None = None) -> list[str]:
    """Reverse-ladder checks (reported, never scored): per-point min/max from
    `reverse_ladder.checks`; no spread floors. Report-only names without
    limits are skipped."""
    m = manifest or load_manifest()
    fails: list[str] = []
    for p in _points(response):
        for name, chk in m["reverse_ladder"]["checks"].items():
            if "min" not in chk and "max" not in chk:
                continue
            val = p["vals"].get(name)
            if val is None or val != val:
                fails.append(f"{p['id']}: {name}: no value")
                continue
            if "min" in chk and val < chk["min"]:
                fails.append(f"{p['id']}: {name}={val:.6g} < min {chk['min']}")
            if "max" in chk and val > chk["max"]:
                fails.append(f"{p['id']}: {name}={val:.6g} > max {chk['max']}")
    return fails


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build")
    b.add_argument("out_dir")
    b.add_argument("--sabotage-polarity", action="store_true",
                   help="negative control: swap the stimulus signs")
    b.add_argument("--no-reverse", action="store_true",
                   help="omit the supplemental reverse ladder")
    b.add_argument("--suppress-reverse-flip", action="store_true",
                   help="reverse negative control: the reverse stimulus never flips")
    g = sub.add_parser("grade")
    g.add_argument("--reverse", action="store_true",
                   help="grade the reverse checks only (exit status and --expect-fail apply to them)")
    g.add_argument("response", nargs="+")
    g.add_argument("--expect-fail", action="store_true",
                   help="negative control: succeed only if grading FAILS")
    args = ap.parse_args(argv)
    if args.cmd == "build":
        out = Path(args.out_dir)
        out.mkdir(parents=True, exist_ok=True)
        (out / "tb_regeneration.spice").write_text(build_netlist(
            sabotage_polarity=args.sabotage_polarity, reverse=not args.no_reverse,
            suppress_reverse_flip=args.suppress_reverse_flip))
        for name, req in build_requests(reverse=not args.no_reverse).items():
            (out / f"request-{name}.json").write_text(json.dumps(req, indent=2) + "\n")
        print(f"wrote {out}/request-{{process,temperature,supply,graded-cold,graded-hot}}.json")
        return 0
    merged = merge_responses([json.loads(Path(x).read_text()) for x in args.response])
    if args.reverse:
        fails = grade_reverse(merged)
        for f in fails[:40]:
            print("FAIL:", f)
        print(f"{'FAIL' if fails else 'PASS'}: {len(fails)} reverse check failure(s)")
        return (0 if fails else 1) if args.expect_fail else (1 if fails else 0)
    has_rev = any(x["name"] == "td_od50_rev_ns"
                  for x in merged["corners"][0]["measurements"])
    rfails = grade_reverse(merged) if has_rev else None
    fails = grade(merged)
    for f in fails[:40]:
        print("FAIL:", f)
    print(f"{'FAIL' if fails else 'PASS'}: {len(fails)} check failure(s)")
    if rfails is not None:  # reported, never scored: no effect on the exit status
        for f in rfails[:40]:
            print("REVERSE (reported, not scored):", f)
        print(f"REVERSE (reported, not scored): {len(rfails)} check failure(s)")
    return (0 if fails else 1) if args.expect_fail else (1 if fails else 0)


if __name__ == "__main__":
    sys.exit(main())
