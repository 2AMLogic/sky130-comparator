def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    h.update(path.read_bytes())
    return f"sha256:{h.hexdigest()}"


def _load_run_module():
    """Load sim/comparator-decision/run.py by path (its directory name is
    not a package name), the same way sim/tests does."""
    spec = importlib.util.spec_from_file_location("t1_items56_run", RUN_PY)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


class _StubPdkInfo:
    """`.ngspice_lib` is all `_deck_preamble` reads; the .lib line it feeds
    is stripped anyway (klt sim writes its own per corner)."""

    ngspice_lib = "/nonexistent/sky130.lib.spice"


def _strip_deck_machinery(deck: str) -> list[str]:
    """Drop the lines klt sim owns: the .lib/.temp cards, the .control
    block (inclusive) and .end. Everything else -- title comment, params,
    stimuli, the DUT include/fragment -- is kept verbatim."""
    out: list[str] = []
    in_control = False
    for line in deck.splitlines():
        s = line.strip()
        if s == ".control":
            in_control = True
            continue
        if s == ".endc":
            in_control = False
            continue
        if in_control:
            continue
        if s.startswith(".lib ") or s.startswith(".temp ") or s == ".end":
            continue
        out.append(line)
    return out


def _body_header(provenance_line: str) -> list[str]:
    frag_sha = _sha256_file(FRAGMENT)
    return [
        f"* {provenance_line}",
        "* Generated by scripts/t1-items56-envelope.py --write from run.py's own deck",
        f"* builders; DUT fragment testbench/comparator_core.spice sha256 {frag_sha[7:]}.",
        "* Do not hand-edit: regenerate, or the --check gate fails.",
        "* .lib/.temp/.control/.end omitted -- klt sim writes its own per corner.",
    ]


def _emit_bodies(run) -> dict[str, str]:
    """One body per testbench family, as text."""
    info = _StubPdkInfo()
    bodies: dict[str, str] = {}

    regen = _strip_deck_machinery(run._regen_deck(info, "tt", 27.0, 50.0, "x"))
    bodies["regen-body.spice"] = "\n".join(
        _body_header("t1 item-5 decision-time body -- run.py _regen_deck at vindiff=+50mV")
        + regen
    ) + "\n"

    kick = _strip_deck_machinery(run._kickback_deck(info, "tt", 27.0, "loaded", "x"))
    bodies["kickback-body-loaded.spice"] = "\n".join(
        _body_header("t1 item-5 kickback body (loaded, Rs=1000ohm) -- run.py _kickback_deck")
        + kick
    ) + "\n"

    noise = _strip_deck_machinery(run._noise_deck(info, "tt", 27.0))
    bodies["noise-body.spice"] = "\n".join(
        _body_header("t1 item-5 input-referred-noise body -- run.py _noise_deck loop-broken sub-model")
        + noise
    ) + "\n"

    # The offset body parametrizes the differential input so one calibration
    # request can sweep vindiff through corners.params: the two literal
    # source values become {expr} over one .param. This is the one deliberate
    # divergence from _pickoff_deck's text, stated here and checked by --check.
    pick = _strip_deck_machinery(run._pickoff_deck(info, "tt_mm", 27.0, 0.0, "x"))
    vcm = run.VCM
    src_p = f"Vinp VINP 0 dc {vcm}"
    src_n = f"Vinn VINN 0 dc {vcm}"
    param_line = f".param vind_diff_mv = 0"
    out: list[str] = []
    for line in pick:
        if line == src_p:
            out.append(f"Vinp VINP 0 dc {{{vcm} + vind_diff_mv/2000}}")
        elif line == src_n:
            out.append(f"Vinn VINN 0 dc {{{vcm} - vind_diff_mv/2000}}")
        else:
            out.append(line)
        if line.startswith(".param vdd_val"):
            out.append(param_line)
    bodies["offset-pickoff-body.spice"] = "\n".join(
        _body_header(
            "t1 item-6 offset pick-off body -- run.py _pickoff_deck at vindiff=0, "
            "input sources parametrized over .param vind_diff_mv for the calibration sweep"
        )
        + out
    ) + "\n"
    return bodies


def _graded_corner_block() -> dict:
    process = sorted({p for p, _ in GRADED_PVT})
    temps = sorted({t for _, t in GRADED_PVT})
    graded = set(GRADED_PVT)
    exclude = [
        {"process": p, "temperature_c": t}
        for p in process
        for t in temps
        if (p, t) not in graded
    ]
    # `exclude` is a TOP-LEVEL request key (the klt-pilot requests'
    # convention); inside `corners` it would be an unknown key.
    return {
        "corners": {"process": process, "temperature_c": temps},
        "exclude": exclude,
    }


def _batch_block() -> dict:
    # Host policy: every batch submit waits for capacity (600 s) rather than
    # failing on a burst; runner skew is recorded (warn), not fatal.
    return {"runner_version_check": "warn", "capacity_wait_s": 600}


def _emit_requests(run, gain_v_per_v: float | None) -> dict[str, str]:
    def dump(obj: object) -> str:
        return json.dumps(obj, indent=2) + "\n"

    requests: dict[str, str] = {}

    # -- item 5: decision time ------------------------------------------------
    requests["regen-request.json"] = dump({
        "netlist": "bodies/regen-body.spice",
        "engine": "ngspice",
        "models": {"pdk": "sky130A", "lib": "libs.tech/combined/sky130.lib.spice"},
        **_graded_corner_block(),
        "batch": _batch_block(),
        "analysis": {"kind": "tran", "args": "0.005n 45.1n"},
        "measurements": [
            {
                "name": "t_dec", "unit": "s",
                "limits": {"max": T_DEC_MAX_S},
                "spec_row": ROW_T_DEC,
                "spice": ".meas tran t_dec TRIG v(CLK) VAL=0.9 RISE=1 "
                         "TARG par('v(OUTP) - v(OUTN)') VAL=0.9 RISE=1",
            },
            {
                "name": "t_dec_abs", "unit": "s",
                "spice": ".meas tran t_dec_abs WHEN par('v(OUTP) - v(OUTN)')=0.9 RISE=1",
            },
        ],
        "options": {"timeout_s": 450, "ngspice_init": ["set measureprec=12", "set numdgt=12"]},
    })

    # -- item 5: kickback ------------------------------------------------
    requests["kickback-request.json"] = dump({
        "netlist": "bodies/kickback-body-loaded.spice",
        "engine": "ngspice",
        "models": {"pdk": "sky130A", "lib": "libs.tech/combined/sky130.lib.spice"},
        **_graded_corner_block(),
        "batch": _batch_block(),
        "analysis": {"kind": "tran", "args": "0.005n 45.1n"},
        "measurements": [
            {
                "name": "vinp_pk_mv", "unit": "mV",
                "limits": {"max": KICKBACK_MAX_MV},
                "spec_row": ROW_KICKBACK,
                "spice": ".meas tran vinp_pk_mv MAX par('abs(v(VINP) - 0.925)*1000') FROM=0 TO=45.1n",
            },
            {
                "name": "vinn_pk_mv", "unit": "mV",
                "limits": {"max": KICKBACK_MAX_MV},
                "spec_row": ROW_KICKBACK,
                "spice": ".meas tran vinn_pk_mv MAX par('abs(v(VINN) - 0.875)*1000') FROM=0 TO=45.1n",
            },
        ],
        "options": {"timeout_s": 450, "ngspice_init": ["set measureprec=12", "set numdgt=12"]},
    })

    # -- item 5: input-referred noise (AC, loop-broken sub-model) -----------
    fstart = int(run.NOISE_FSTART_HZ)
    fstop = int(run.NOISE_FSTOP_HZ)
    requests["noise-request.json"] = dump({
        "netlist": "bodies/noise-body.spice",
        "engine": "ngspice",
        "models": {"pdk": "sky130A", "lib": "libs.tech/combined/sky130.lib.spice"},
        **_graded_corner_block(),
        "batch": _batch_block(),
        "analysis": {"kind": "noise", "args": f"v(outp1,outn1) Vinp dec 20 {fstart} {fstop} 20"},
        "measurements": [
            {
                "name": "inoise_diff_mv", "unit": "mV",
                "limits": {"max": NOISE_MAX_MV},
                "spec_row": ROW_NOISE_AC,
                "expr": "inoise_total*sqrt(2)*1000",
            },
            {
                "name": "inoise_band_v", "unit": "V",
                "noise": {"quantity": "inoise", "band_hz": [fstart, fstop]},
            },
        ],
        "options": {
            "timeout_s": 600,
            "ngspice_init": ["option sparse", "set measureprec=12", "set numdgt=12"],
        },
    })

    # -- item 6: offset calibration -----------------------------------------
    calib_points = [1.0, 2.0, 5.0, 10.0]
    requests["offset-calib-request.json"] = dump({
        "netlist": "bodies/offset-pickoff-body.spice",
        "engine": "ngspice",
        "models": {"pdk": "sky130A", "lib": "libs.tech/combined/sky130.lib.spice"},
        "corners": {
            "process": ["tt"],
            "temperature_c": [MC_TEMP_C],
            "params": {"vind_diff_mv": calib_points},
        },
        "batch": _batch_block(),
        "analysis": {"kind": "tran", "args": "0.002n 7.6n"},
        "measurements": [
            {
                "name": "pkdiff_mv", "unit": "mV",
                "spice": ".meas tran pkdiff_mv FIND par('(v(OUTP) - v(OUTN))*1000') AT=5.75n",
            },
        ],
        "options": {"timeout_s": 300, "ngspice_init": ["set measureprec=12", "set numdgt=12"]},
    })

    if gain_v_per_v is not None:
        gain_txt = f"{gain_v_per_v:.6f}"
        meas = {
            "name": "vos_ir_mv", "unit": "mV",
            "spec_row": ROW_OFFSET,
            "spice": f".meas tran vos_ir_mv FIND par('(v(OUTP) - v(OUTN))*1000/{gain_txt}') AT=5.75n",
        }
        for corner in MC_CORNERS:
            requests[f"offset-mc-{corner}-request.json"] = dump({
                "netlist": "bodies/offset-pickoff-body.spice",
                "engine": "ngspice",
                "models": {"pdk": "sky130A", "lib": "libs.tech/combined/sky130.lib.spice"},
                "corners": {"process": [corner], "temperature_c": [MC_TEMP_C]},
                "monte_carlo": {
                    "n": MC_N, "seed": MC_SEED, "vary": "mismatch",
                    "seed_mode": "sequential",
                },
                "batch": _batch_block(),
                "analysis": {"kind": "tran", "args": "0.002n 7.6n"},
                "measurements": [meas],
                "options": {"timeout_s": 300, "ngspice_init": ["set measureprec=12", "set numdgt=12"]},
            })
            requests[f"offset-ctl-{corner}-request.json"] = dump({
                "netlist": "bodies/offset-pickoff-body.spice",
                "engine": "ngspice",
                "models": {"pdk": "sky130A", "lib": "libs.tech/combined/sky130.lib.spice"},
                "corners": {"process": [corner], "temperature_c": [MC_TEMP_C]},
                "monte_carlo": {
                    "n": MC_N, "seed": MC_CONTROL_SEED, "vary": "mismatch",
                    "seed_mode": "sequential", "mismatch_scale": MC_CONTROL_SCALE,
                },
                "batch": _batch_block(),
                "analysis": {"kind": "tran", "args": "0.002n 7.6n"},
                "measurements": [meas],
                "options": {"timeout_s": 300, "ngspice_init": ["set measureprec=12", "set numdgt=12"]},
            })
        # Determinism control: same seed sequence as the nominal tt_mm run,
        # per-instance mismatch off -- the committed campaigns' negative
        # control (stdev must be exactly 0 across draws).
        requests["offset-det-tt_mm-request.json"] = dump({
            "netlist": "bodies/offset-pickoff-body.spice",
            "engine": "ngspice",
            "models": {"pdk": "sky130A", "lib": "libs.tech/combined/sky130.lib.spice"},
            "corners": {"process": ["tt_mm"], "temperature_c": [MC_TEMP_C]},
            "monte_carlo": {
                "n": MC_N, "seed": MC_SEED, "vary": "mismatch",
                "seed_mode": "sequential", "mismatch_scale": 0,
            },
            "batch": _batch_block(),
            "analysis": {"kind": "tran", "args": "0.002n 7.6n"},
            "measurements": [meas],
            "options": {"timeout_s": 300, "ngspice_init": ["set measureprec=12", "set numdgt=12"]},
        })
    return requests


def _emit_yield_inputs() -> dict[str, str]:
    def dump(obj: object) -> str:
        return json.dumps(obj, indent=2) + "\n"

    spec_limits = {
        "confidence": 0.95,
        "target_ci_halfwidth": 0.01,
        "measurements": {
            "vos_ir_mv": {
                "min": -OFFSET_WINDOW_MV,
                "max": OFFSET_WINDOW_MV,
                "target_sigma": OFFSET_TARGET_SIGMA,
                "spec_row": ROW_OFFSET,
            }
        },
    }
    return {f"yield/{name}": dump(obj) for name, obj in
            [("spec-limits.json", spec_limits)]}


def _fit_gain_from_calib_report(report: dict) -> float:
    """Zero-intercept least squares of pkdiff_mv over vindiff_mv, from the
    calibration report's per-corner values -- the same fit run.py offset
    applies to its 4-point sweep."""
    xs: list[float] = []
    ys: list[float] = []
    for corner in report.get("corners", []):
        params = (corner.get("params") or {})
        if "vind_diff_mv" not in params:
            continue
        for m in corner.get("measurements", []):
            if m.get("name") == "pkdiff_mv" and isinstance(m.get("value"), (int, float)):
                xs.append(float(params["vind_diff_mv"]))
                ys.append(float(m["value"]))
    if len(xs) != 4:
        raise SystemExit(
            f"calibration report does not carry 4 pkdiff_mv values (found {len(xs)})"
        )
    denom = sum(x * x for x in xs)
    if denom <= 0:
        raise SystemExit("calibration sweep degenerate")
    return sum(x * y for x, y in zip(xs, ys)) / denom


def _generated_files(gain_v_per_v: float | None) -> dict[str, str]:
    run = _load_run_module()
    files = {}
    files.update({f"bodies/{k}": v for k, v in _emit_bodies(run).items()})
    files.update(_emit_requests(run, gain_v_per_v))
    files.update(_emit_yield_inputs())
    if gain_v_per_v is not None:
        files["offset-gain.json"] = json.dumps({
            "gain_v_per_v": round(gain_v_per_v, 6),
            "fit": "zero-intercept least squares of pkdiff_mv over vindiff_mv",
            "source": "report-offset-calib.json",
        }, indent=2) + "\n"
    return files


def cmd_write(update: bool, calib_report: str | None) -> int:
    gain: float | None = None
    if GAIN_FILE.exists():
        gain = json.loads(GAIN_FILE.read_text())["gain_v_per_v"]
    if calib_report is not None:
        report = json.loads(Path(calib_report).read_text())
        gain = _fit_gain_from_calib_report(report)
        print(f"fitted pick-off gain: {gain:.6f} V/V")
    if gain is None:
        print("note: no gain recorded yet; Monte Carlo requests deferred "
              "(run the calibration leg, then --write --calib-report)")
    files = _generated_files(gain)
    KLT_T1_DIR.mkdir(parents=True, exist_ok=True)
    (KLT_T1_DIR / "bodies").mkdir(exist_ok=True)
    (KLT_T1_DIR / "yield").mkdir(exist_ok=True)
    changed = []
    for rel, text in sorted(files.items()):
        path = KLT_T1_DIR / rel
        if path.exists() and path.read_text() == text:
            continue
        if path.exists() and not update:
            print(f"REFUSED: {rel} exists and would change (use --update)")
            return 1
        path.write_text(text)
        changed.append(rel)
    print(f"{len(changed)} file(s) written" + (": " + ", ".join(changed) if changed else ""))
    return 0


def _check_tree(root: Path) -> list[str]:
    """The --check core, over a tree root: regenerate everything and compare.
    Returns a list of problems (empty == clean)."""
    global KLT_T1_DIR, FRAGMENT, MANIFEST
    saved = KLT_T1_DIR, FRAGMENT, MANIFEST
    problems: list[str] = []
    try:
        KLT_T1_DIR = root / "sim/comparator-decision/klt-t1"
        FRAGMENT = root / "sim/comparator-decision/testbench/comparator_core.spice"
        MANIFEST = root / "manifests/sky130-comparator.json"
        gain = None
        gain_file = KLT_T1_DIR / "offset-gain.json"
        if gain_file.exists():
            gain = json.loads(gain_file.read_text())["gain_v_per_v"]
        files = _generated_files(gain)
        for rel, text in sorted(files.items()):
            path = KLT_T1_DIR / rel
            if not path.exists():
                problems.append(f"missing: {rel}")
            elif path.read_text() != text:
                problems.append(f"drifted: {rel}")
        # Fragment hash binding: each body header names the fragment sha it
        # was generated against; a changed fragment shows up as body drift
        # above, but say which anchor moved when it does.
        for name in ["regen-body.spice", "kickback-body-loaded.spice",
                     "noise-body.spice", "offset-pickoff-body.spice"]:
            path = KLT_T1_DIR / "bodies" / name
            if not path.exists():
                continue
            m = re.search(r"sha256 ([0-9a-f]{64})", path.read_text())
            if m and m.group(1) != _sha256_file(FRAGMENT)[7:]:
                problems.append(f"stale fragment anchor: bodies/{name}")
        # Report/pin agreement: every manifest item-5/6 citation's
        # content_hash must match the pinned artifact as it reads today.
        manifest = json.loads(MANIFEST.read_text())
        evidence = manifest.get("evidence", {})
        for item in ("5", "6"):
            entries = evidence.get(item, [])
            if isinstance(entries, dict):
                entries = [entries]
            for entry in entries:
                rel = entry.get("file", "")
                pin = entry.get("content_hash")
                path = root / rel
                if not rel or pin is None:
                    continue
                if not path.exists():
                    problems.append(f"citation missing artifact: {rel}")
                    continue
                # A yield citation pins the sha256 of the samples document
                # its report names (resolve it the way the grader does,
                # repo-relative); every other cited report pins its own
                # recorded input hash.
                doc = json.loads(path.read_text())
                samples = doc.get("samples") if isinstance(doc, dict) else None
                if isinstance(samples, str):
                    samples_path = root / samples
                    if not samples_path.exists():
                        problems.append(
                            f"citation names a missing samples document: {samples}"
                        )
                        continue
                    actual = _sha256_file(samples_path)
                else:
                    actual = (doc.get("provenance", {}).get("input", {})
                              .get("content_hash"))
                if actual != pin:
                    problems.append(
                        f"citation pin mismatch: {rel} pinned {pin}, artifact reads {actual}"
                    )
    finally:
        KLT_T1_DIR, FRAGMENT, MANIFEST = saved
    return problems


def cmd_check() -> int:
    problems = _check_tree(REPO_ROOT)
    for p in problems:
        print(f"FAIL: {p}")
    print("check: " + ("clean" if not problems else f"{len(problems)} problem(s)"))
    return 1 if problems else 0


def cmd_pins() -> int:
    pins: dict[str, str] = {}
    for row, rel in ITEM5_REPORTS.items():
        report = json.loads((KLT_T1_DIR / rel).read_text())
        pins[rel] = report["provenance"]["input"]["content_hash"]
    for corner, rel in ITEM6_REPORTS.items():
        samples = ITEM6_SAMPLES[corner]
        pins[rel] = _sha256_file(KLT_T1_DIR / samples)
    print(json.dumps(pins, indent=2))
    return 0


def cmd_yield_step(corner: str) -> int:
    if corner not in MC_CORNERS:
        raise SystemExit(f"corner must be one of {MC_CORNERS}")
    nominal = KLT_T1_DIR / f"report-offset-mc-{corner}.json"
    control = KLT_T1_DIR / f"report-offset-ctl-{corner}.json"
    for p in (nominal, control):
        if not p.exists():
            raise SystemExit(f"missing {p.name}: run both Monte Carlo legs first")
    out = YIELD_DIR / f"samples-{corner}.json"
    # Repo-relative paths from the repo root, the convention committed
    # artifacts follow (klt yield's report echoes the samples path as given,
    # and the signoff grader resolves it against its own working directory;
    # yield-samples' derivation block records the same paths verbatim).
    rel = lambda p: str(p.relative_to(REPO_ROOT))
    argv = [
        "uvx", "--from", YIELD_UVX_FROM, "klt", "yield-samples",
        rel(nominal), "--negative-control", rel(control),
        "--description",
        f"per-instance mismatch sigma scaled {MC_CONTROL_SCALE:g}x "
        f"(monte_carlo.mismatch_scale), seed {MC_CONTROL_SEED}",
        "--format", "json",
    ]
    proc = subprocess.run(argv, capture_output=True, text=True, cwd=str(REPO_ROOT))
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout + proc.stderr)
        raise SystemExit(f"klt yield-samples exited {proc.returncode}")
    doc = json.loads(proc.stdout)
    # Run provenance, the block the yield report records on its own source:
    # seed/N from the campaign, the corner matrix the row's MC basis covers,
    # and the RNG identity (sky130 AGAUSS per-instance terms via the
    # mc_mm_switch the mismatch_scale leg scaled).
    doc["provenance"] = {
        "seed": MC_SEED,
        "rng": "ngspice AGAUSS per-instance mismatch (sky130 mc_mm_switch)",
        "draws_per_population": MC_N,
        "common_random_numbers": False,
        "corner_matrix": MC_CORNERS,
    }
    out.write_text(json.dumps(doc, indent=2) + "\n")
    print(f"wrote {out}")
    return 0


class SelfTests(unittest.TestCase):
    """Hermetic negative controls for --check, on a scratch copy of the
    real tree: each case must turn a clean check into exactly the named
    problem, and an untouched copy must stay clean."""

    def _scratch(self) -> Path:
        tmp = tempfile.mkdtemp(prefix="t1-items56-selftest-")
        root = Path(tmp) / "repo"
        shutil.copytree(REPO_ROOT, root, ignore=shutil.ignore_patterns(".git", ".loom*"))
        self.addCleanup(shutil.rmtree, tmp, ignore_errors=True)
        return root

    def test_clean_copy_passes(self):
        root = self._scratch()
        self.assertEqual(_check_tree(root), [])

    def test_body_edit_detected(self):
        root = self._scratch()
        body = root / "sim/comparator-decision/klt-t1/bodies/regen-body.spice"
        body.write_text(body.read_text().replace("0.925", "0.926"))
        problems = _check_tree(root)
        self.assertTrue(any("drifted: bodies/regen-body.spice" in p for p in problems))

    def test_fragment_move_detected(self):
        root = self._scratch()
        frag = root / "sim/comparator-decision/testbench/comparator_core.spice"
        frag.write_text(frag.read_text() + "* edited\n")
        problems = _check_tree(root)
        self.assertTrue(any("drifted: bodies/" in p for p in problems))

    def test_request_edit_detected(self):
        root = self._scratch()
        req = root / "sim/comparator-decision/klt-t1/regen-request.json"
        doc = json.loads(req.read_text())
        doc["measurements"][0]["limits"]["max"] = 99e-9
        req.write_text(json.dumps(doc, indent=2) + "\n")
        problems = _check_tree(root)
        self.assertTrue(any("drifted: regen-request.json" in p for p in problems))

    def test_manifest_pin_mismatch_detected(self):
        root = self._scratch()
        # Plant a citation of a real-shaped report with a wrong pin: the
        # report needs only the provenance.input.content_hash --check reads.
        report = root / "sim/comparator-decision/klt-t1/report-regen.json"
        report.parent.mkdir(parents=True, exist_ok=True)
        report.write_text(json.dumps(
            {"provenance": {"input": {"content_hash": "sha256:" + "1" * 64}}}) + "\n")
        manifest = root / "manifests/sky130-comparator.json"
        doc = json.loads(manifest.read_text())
        doc.setdefault("evidence", {})["5"] = [
            {"file": "sim/comparator-decision/klt-t1/report-regen.json",
             "rows": ["t_dec"], "content_hash": "sha256:" + "0" * 64}
        ]
        manifest.write_text(json.dumps(doc, indent=2) + "\n")
        problems = _check_tree(root)
        self.assertTrue(any("citation pin mismatch" in p for p in problems))

    def test_citation_missing_artifact_detected(self):
        root = self._scratch()
        manifest = root / "manifests/sky130-comparator.json"
        doc = json.loads(manifest.read_text())
        doc.setdefault("evidence", {})["6"] = [
            {"file": "sim/comparator-decision/klt-t1/yield/report-fs_mm.json",
             "rows": ["offset_sigma"], "content_hash": "sha256:" + "2" * 64}
        ]
        manifest.write_text(json.dumps(doc, indent=2) + "\n")
        problems = _check_tree(root)
        self.assertTrue(any("citation missing artifact" in p for p in problems))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--selftest", action="store_true")
    mode.add_argument("--pins", action="store_true")
    mode.add_argument("--yield-step", metavar="CORNER")
    parser.add_argument("--update", action="store_true")
    parser.add_argument("--calib-report", metavar="JSON")
    args = parser.parse_args(argv)

    if args.selftest:
        suite = unittest.defaultTestLoader.loadTestsFromTestCase(SelfTests)
        result = unittest.TextTestRunner(verbosity=2).run(suite)
        return 0 if result.wasSuccessful() else 1
    if args.write:
        return cmd_write(args.update, args.calib_report)
    if args.check:
        return cmd_check()
    if args.pins:
        return cmd_pins()
    if args.yield_step:
        return cmd_yield_step(args.yield_step)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
