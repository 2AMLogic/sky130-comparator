#!/usr/bin/env python3
"""T1 items 5 and 6 envelope generator (issue #188).

Emits the `klt sim` request bodies and request JSONs that make T1 item 5
("full corner verification vs a ratified spec") and item 6 ("statistical
claims carry Monte Carlo evidence") gradeable for this block, and derives
the item-6 `klt yield` sample-set documents and spec-limits file the yield
reports are graded from. Nothing here is hand-edited after the fact: every
committed artifact under `sim/comparator-decision/klt-t1/` that this script
owns is regenerated byte-for-byte by `--write` and verified by `--check`,
the same discipline `scripts/characterization-envelope.py` applies to the
item-8 citation.

What it emits, and why each piece is the shape it is:

* **Bodies** are frozen snapshots of `run.py`'s own deck builders
  (`_regen_deck` at +50 mV, `_kickback_deck` `loaded`,
  `_noise_deck`, `_pickoff_deck` at vindiff 0), generated by importing
  `run.py` -- never hand-typed -- with the deck machinery `klt sim` owns
  (`.lib`, `.temp`, the `.control` block, `.end`) stripped. Each body header
  records the sha256 of `testbench/comparator_core.spice` it was generated
  against, and `--check` re-verifies that hash, so a design edit surfaces as
  a stale body rather than silently grading an old circuit.
* **Item-5 requests** run the seven graded PVT corners per testbench family
  with the ratified target bound copied into `measurements[].limits` and the
  row id in `measurements[].spec_row`, so `klt signoff` derives (not merely
  asserts) each row's coverage from the envelope itself.
* **The offset calibration request** re-derives the pick-off gain the same
  way `run.py offset` does (a 4-point ideal-device vindiff sweep at the
  plain `tt` corner, zero-intercept least squares) through `corners.params`,
  and `--write --calib-report` bakes the fitted gain into the Monte Carlo
  requests' measurement card, so the MC samples are input-referred mV using
  a constant the campaign itself measured.
* **The Monte Carlo requests** reproduce the committed campaigns'
  convention (`_mm` corner, seed 1, sequential per-draw seeds, N=200) with
  `monte_carlo.vary: "mismatch"`, plus a known-bad leg
  (`mismatch_scale: 4`, independently seeded) for `klt yield`'s
  negative-control check and a same-seed mismatch-off leg
  (`mismatch_scale: 0`) for this repo's deterministic-control convention.
* **The yield inputs** (`spec-limits.json`, and the sample-set documents
  derived per corner by `klt yield-samples`) state the ratified Offset sigma
  row as `target_sigma: 3` over the +/-15 mV target window -- the row's
  "<= 15 mV, 3-sigma" bound read as "mean +/- 3-sigma inside the window" --
  with no `target_yield` (the row ratifies no yield fraction; a measurement
  with no target is `reported`, and `target_sigma` met is what grades).

Usage:
    python3 scripts/t1-items56-envelope.py --write [--update]
        (re)generate bodies + requests + yield inputs under
        sim/comparator-decision/klt-t1/. Without --update, refuses to
        overwrite a committed file whose bytes would change.
    python3 scripts/t1-items56-envelope.py --write --calib-report <json>
        additionally (re)emit the four Monte Carlo requests, baking the
        gain fitted from the committed calibration report.
    python3 scripts/t1-items56-envelope.py --yield-step <corner>
        derive sim/comparator-decision/klt-t1/yield/samples-<corner>.json
        from the committed nominal + known-bad Monte Carlo reports via
        `klt yield-samples` (uvx, klayout-tools[yield]==0.9.2), stamping the
        run provenance the report records (seed, N, corner matrix).
    python3 scripts/t1-items56-envelope.py --pins
        print the manifest citation pins (content_hash per cited artifact).
    python3 scripts/t1-items56-envelope.py --check
        verify every committed artifact this script owns regenerates
        byte-for-byte, the body fragment hashes still match, and the
        manifest's item-5/6 citation pins match the committed artifacts.
    python3 scripts/t1-items56-envelope.py --selftest
        hermetic negative-control suite for --check (scratch tree; nothing
        outside a temp dir is read or written).

Stdlib only, like every gate script in scripts/: no klt, no PDK needed for
--write/--check/--pins/--selftest (deck construction uses a stub PdkInfo,
exactly the shape sim/tests/test_comparator_decision.py fakes).
"""

